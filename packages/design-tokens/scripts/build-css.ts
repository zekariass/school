/**
 * Generates generated/theme.css (Tailwind 4 + shadcn/ui variables) from src/tokens.ts.
 *
 *   node scripts/build-css.ts           write the file
 *   node scripts/build-css.ts --check   exit 1 if the committed file is stale (CI)
 *
 * Runs on Node's built-in TypeScript type stripping (Node >= 22.18).
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

import { colors, palette, radii, shadows, typography, type SemanticColors } from '../src/tokens.ts';

const OUTPUT = new URL('../generated/theme.css', import.meta.url);

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const fontStack = (fonts: readonly string[]) =>
  fonts.map((f) => (f.includes(' ') || /^[A-Z]/.test(f) ? `"${f}"` : f)).join(', ');

function semanticVars(set: SemanticColors, indent: string): string {
  return Object.entries(set)
    .map(([name, value]) => `${indent}--${kebab(name)}: ${value};`)
    .join('\n');
}

function render(): string {
  const scales = Object.entries(palette)
    .flatMap(([name, scale]) =>
      typeof scale === 'string'
        ? [`  --color-${name}: ${scale};`]
        : Object.entries(scale).map(([step, value]) => `  --color-${name}-${step}: ${value};`),
    )
    .join('\n');

  const radius = Object.entries(radii)
    .map(([name, px]) => `  --radius-${name}: ${px === 9999 ? '9999px' : `${px / 16}rem`};`)
    .join('\n');

  const fonts = Object.entries(typography.fontFamily)
    .map(([name, stack]) => `  --font-${name}: ${fontStack(stack)};`)
    .join('\n');

  const textSizes = Object.entries(typography.fontSize)
    .map(([name, { size, lineHeight }]) => `  --text-${name}: ${size / 16}rem;\n  --text-${name}--line-height: ${lineHeight};`)
    .join('\n');

  const shadowVars = Object.entries(shadows)
    .map(([name, value]) => `  --shadow-${name}: ${value};`)
    .join('\n');

  const semanticTheme = Object.keys(colors.light)
    .map((name) => `  --color-${kebab(name)}: var(--${kebab(name)});`)
    .join('\n');

  return `/*
 * GENERATED by packages/design-tokens/scripts/build-css.ts from src/tokens.ts.
 * Do not edit by hand. Run \`npm run codegen -w @school/design-tokens\`.
 *
 * Usage (apps/web globals.css, after \`@import "tailwindcss";\`):
 *   @import "@school/design-tokens/theme.css";
 * Dark mode: add the \`dark\` class to <html>.
 */

@theme {
${scales}

${radius}

${fonts}

${textSizes}

${shadowVars}
}

:root {
${semanticVars(colors.light, '  ')}
}

.dark {
${semanticVars(colors.dark, '  ')}
}

@theme inline {
${semanticTheme}
}
`;
}

const css = render();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // missing file is stale
  }
  if (current !== css) {
    console.error('generated/theme.css is out of date. Run: npm run codegen -w @school/design-tokens');
    process.exit(1);
  }
  console.log('generated/theme.css is up to date.');
} else {
  mkdirSync(new URL('.', OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, css);
  console.log('Wrote generated/theme.css');
}
