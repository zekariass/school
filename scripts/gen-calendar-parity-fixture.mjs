// Generates apps/backend/src/test/resources/imports/calendar-parity.csv: for every Gregorian day from 1900-01-01
// to 2100-12-31, the Ethiopian civil date computed by packages/calendar (the TypeScript source of truth).
// The Java port in com.nemaz.school.imports.domain.EthiopianCalendar is tested against it (CalendarParityTest).
//
//   node scripts/gen-calendar-parity-fixture.mjs
//
// Each line: "gy-gm-gd,ey-em-ed". Run again only when packages/calendar/src/convert.ts changes.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ethiopianToGregorian, gregorianToEthiopian } from '../packages/calendar/src/convert.ts';

const out = fileURLToPath(
  new URL('../apps/backend/src/test/resources/imports/calendar-parity.csv', import.meta.url),
);
const lines = ['# gregorian,ethiopian (generated by scripts/gen-calendar-parity-fixture.mjs; do not edit)'];
const start = Date.UTC(1900, 0, 1);
const end = Date.UTC(2100, 11, 31);
for (let t = start; t <= end; t += 86_400_000) {
  const d = new Date(t);
  const g = { year: d.getUTCFullYear(), month: d.getUTCMonth() + 1, day: d.getUTCDate() };
  const e = gregorianToEthiopian(g);
  const back = ethiopianToGregorian(e);
  if (back.year !== g.year || back.month !== g.month || back.day !== g.day) {
    throw new Error(`TypeScript round trip differs for ${JSON.stringify(g)}`);
  }
  lines.push(`${g.year}-${g.month}-${g.day},${e.year}-${e.month}-${e.day}`);
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${lines.length - 1} days to ${out}`);
